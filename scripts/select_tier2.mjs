// Picks the Tier-2 (indexable) swarm pages: the K most distinct pages by
// estimated near-duplicate similarity (MinHash over word 4-gram shingles + LSH
// banding), with a per-language floor so every language is represented.
// Writes deploy/swarm/tier2.js and a private clue manifest (site_clues_v3.json).
//
// Usage: node scripts/select_tier2.mjs [--k 5000] [--n 300000]
import fs from "node:fs";
import path from "node:path";
import { page } from "../deploy/swarm/generate.js";
import STORY_PATHS from "../deploy/story_paths.js";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? Number(process.argv[i + 1]) : d; };
const K = arg("--k", 5000), N = arg("--n", 300000);
const LANG_FLOOR = 150;
const H = 32, BANDS = 8, ROWS = H / BANDS;

const staticSlugs = new Set(STORY_PATHS.filter((p) => /^geocities\/[^/]+\.html$/.test(p)).map((p) => p.slice(10, -5)));

function fnv(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) h = Math.imul(h ^ str.charCodeAt(i), 0x01000193);
  return h >>> 0;
}
const A = Array.from({ length: H }, (_, i) => (fnv("a" + i) | 1) >>> 0);
const Bc = Array.from({ length: H }, (_, i) => fnv("b" + i));

function contentText(hp) {
  const out = [hp.title, hp.marquee || ""];
  for (const s of hp.sections) {
    out.push(s.h, ...(s.p || []), ...(s.list || []), ...(s.ol || []), ...(s.p2 || []), ...(s.pre || []));
    for (const g of s.guestbook || []) out.push(g.text);
  }
  return out.join(" ").toLowerCase().replace(/<[^>]+>/g, " ");
}

const sigs = new Uint32Array(N * H);
const lang = new Array(N);
const skip = new Uint8Array(N);
const clues = [];
const t0 = Date.now();
for (let id = 0; id < N; id++) {
  const hp = page(id);
  lang[id] = hp.lang;
  if (staticSlugs.has(hp.slug)) { skip[id] = 1; continue; }
  if (hp.clue) clues.push({ id, slug: hp.slug, tier: "uncommon_node", region: hp.region, text: hp.clue });
  const words = contentText(hp).split(/[\s.,!?;:()"'«»“”„。、！？]+/u).filter(Boolean);
  const base = id * H;
  sigs.fill(0xffffffff, base, base + H);
  const grams = Math.max(1, words.length - 3);
  for (let w = 0; w < grams; w++) {
    const x = fnv(words.slice(w, w + 4).join(" "));
    for (let j = 0; j < H; j++) {
      const v = (Math.imul(A[j], x) + Bc[j]) >>> 0;
      if (v < sigs[base + j]) sigs[base + j] = v;
    }
  }
  if (id % 50000 === 0 && id) console.error(`  hashed ${id} (${((Date.now() - t0) / 1000).toFixed(0)}s)`);
}

// LSH: bucket by band; estimate each page's max similarity to any bucket-mate.
const maxSim = new Float32Array(N);
const BUCKET_CAP = 64;
for (let b = 0; b < BANDS; b++) {
  const buckets = new Map();
  for (let id = 0; id < N; id++) {
    if (skip[id]) continue;
    let k = "";
    for (let r = 0; r < ROWS; r++) k += sigs[id * H + b * ROWS + r].toString(36) + ".";
    let arr = buckets.get(k);
    if (!arr) buckets.set(k, (arr = []));
    arr.push(id);
  }
  for (const arr of buckets.values()) {
    if (arr.length < 2) continue;
    if (arr.length > BUCKET_CAP) { for (const id of arr) maxSim[id] = Math.max(maxSim[id], 0.9); continue; }
    for (let i = 0; i < arr.length; i++) for (let j = i + 1; j < arr.length; j++) {
      let eq = 0;
      const x = arr[i] * H, y = arr[j] * H;
      for (let h = 0; h < H; h++) if (sigs[x + h] === sigs[y + h]) eq++;
      const s = eq / H;
      if (s > maxSim[arr[i]]) maxSim[arr[i]] = s;
      if (s > maxSim[arr[j]]) maxSim[arr[j]] = s;
    }
  }
}

// Selection: per-language floor first, then globally most distinct. Ties break by id hash.
const order = [];
for (let id = 0; id < N; id++) if (!skip[id]) order.push(id);
order.sort((a, b) => maxSim[a] - maxSim[b] || fnv("t" + a) - fnv("t" + b));
const chosen = new Set();
const perLang = {};
for (const id of order) {
  const l = lang[id];
  if ((perLang[l] || 0) < LANG_FLOOR) { chosen.add(id); perLang[l] = (perLang[l] || 0) + 1; }
}
for (const id of order) {
  if (chosen.size >= K) break;
  if (!chosen.has(id)) { chosen.add(id); perLang[lang[id]] = (perLang[lang[id]] || 0) + 1; }
}

const ids = [...chosen].sort((a, b) => a - b);
// Language hubs list Tier-2 pages in that language (lowest ids first, so they are live earliest).
const hubs = {};
for (const id of ids) (hubs[lang[id]] ||= []).length < 200 && hubs[lang[id]].push(id);
fs.writeFileSync(path.join(ROOT, "deploy", "swarm", "tier2.js"),
  `// Generated by scripts/select_tier2.mjs - the ${ids.length} most distinct swarm pages (indexable tier)\n` +
  `export const LANG_HUBS = ${JSON.stringify(hubs)};\nexport default ${JSON.stringify(ids)};\n`);
fs.writeFileSync(path.join(ROOT, "site_clues_v3.json"), JSON.stringify({ total_clues: clues.length, clues }, null, 1));

const q = (arr, p) => arr[Math.floor(p * (arr.length - 1))].toFixed(2);
const all = order.map((id) => maxSim[id]).sort((a, b) => a - b);
const sel = ids.map((id) => maxSim[id]).sort((a, b) => a - b);
console.error(`pages ${order.length} (shadowed by static ${N - order.length}), ${((Date.now() - t0) / 1000).toFixed(0)}s`);
console.error(`max-similarity  all: p10 ${q(all, 0.1)} p50 ${q(all, 0.5)} p90 ${q(all, 0.9)} p99 ${q(all, 0.99)}   tier2: p50 ${q(sel, 0.5)} max ${q(sel, 1)}`);
console.error(`near-duplicates (>=0.5): ${all.filter((s) => s >= 0.5).length}`);
console.error("tier2 per language:", JSON.stringify(perLang));
console.error(`clues (uncommon_node, private manifest): ${clues.length}`);
